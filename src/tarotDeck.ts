export const tarotDeck = cards.map(card => ({ ...card, image: tarotArt(card.no) }));
export type TarotCard = typeof tarotDeck[number];
export type TarotId = TarotCard['id'];
export const findTarot = (id: string) => tarotDeck.find(card => card.id === id);

export const seasonNames = ['春', '夏', '秋', '冬'] as const;
const levelNames = ['凱風', '順風', '凪', '荒波', '轟沈'] as const;

/** タイプ（mod）から季節。図鑑の並び（春→夏→秋→冬）と同じ。 */
export const seasonOf = (mod: number): Season => (((mod + 3) % 4) as Season);

/** 今日の海の調子に合わせた、札の活かし方。 */
export function tarotTone(level: Level, heavy?: boolean) {
  if (heavy && level >= 3) return levelNames[level] + 'の日に出た札。無理に動かず、休むことを今日の正しい選択にしましょう。';
  if (heavy) return levelNames[level] + 'の日。重く見える札ですが、手放しや気づきには向いた追い風です。';
  return [
    '凱風の日。この札の意味を、思い切って行動に移せます。',
    '順風の日。札の意味を、普段より一歩だけ前に出して試せます。',
    '凪の日。札の意味を、静かに整えるために使いましょう。',
    '荒波の日。札の意味は、守りに使うほど効果的。無理は禁物です。',
    '轟沈の日。札の意味は「休んでいい」という許可として受け取りましょう。',
  ][level];
}

function seeded(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function hash(text: string) {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 16777619);
  return h >>> 0;
}

/**
 * 今日の場に伏せられる札。日付と人から、並びも中身も必ず同じになる（何度開き直しても同じ）。
 * 最近引いた札（recent）は避けるので、選んだ札が数日のうちに重なりにくい。
 * 画面ではこれを裏向きに並べ、ユーザーが気になる一枚を選んで引く。
 */
export function tarotSpread(day: string, key: string, recent: string[], count = 5): TarotCard[] {
  const random = seeded(hash(key + ':' + day));
  const order = [...tarotDeck];
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  const skip = new Set(recent.slice(-(tarotDeck.length - count)));
  return [...order.filter(card => !skip.has(card.id)), ...order.filter(card => skip.has(card.id))].slice(0, count);
}
